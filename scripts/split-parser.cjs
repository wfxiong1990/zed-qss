// Split the generated C source at line boundaries for repository hosting.
// The pieces are included in order and compile as one translation unit.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const src = path.join(__dirname, '..', 'grammar', 'src');
const parser = path.join(src, 'parser.c');
const source = fs.readFileSync(parser, 'utf8');
if (!source.startsWith('/* Automatically @generated by tree-sitter')) {
  throw new Error('Run tree-sitter generate in grammar/ before splitting parser.c');
}

const parts = [];
let part = '';
let depth = 0;
for (const line of source.match(/[^\n]*\n|[^\n]+$/g) || []) {
  const directive = line.match(/^\s*#\s*(if|ifdef|ifndef|endif)\b/);
  if (directive) depth += directive[1] === 'endif' ? -1 : 1;
  if (depth < 0) throw new Error('Unbalanced preprocessor directives');
  part += line;
  if (part.length >= 96 * 1024 && depth === 0 && !/\\\r?\n$/.test(line)) {
    parts.push(part);
    part = '';
  }
}
if (depth !== 0) throw new Error('Unbalanced preprocessor directives');
if (part) parts.push(part);
for (const name of fs.readdirSync(src)) {
  if (/^parser_part_\d+\.inc$/.test(name)) fs.unlinkSync(path.join(src, name));
}
const names = parts.map((contents, i) => {
  const name = `parser_part_${String(i).padStart(3, '0')}.inc`;
  fs.writeFileSync(path.join(src, name), contents);
  return name;
});
const hash = crypto.createHash('sha256').update(source).digest('hex');
fs.writeFileSync(parser, `/* Generated parser, SHA-256 ${hash}; see scripts/split-parser.cjs. */\n` +
  names.map(name => `#include "${name}"\n`).join(''));
console.log(`Split parser into ${names.length} parts`);
